F.localeLabels=setmetatable({},{__mode='k'})
local sorted={}
for ru in pairs(F.english) do sorted[#sorted+1]=ru end
table.sort(sorted,function(a,b) return #a>#b end)
local cache,count={},0
function F.ClientLanguage()
 if type(GetLocale)=='function' then
  local ok,value=pcall(GetLocale)
  if ok and value=='ruRU' then return 'ruRU' end
 end
 return 'enUS'
end
function F.EffectiveLanguage(choice)
 if choice=='ruRU' or choice=='enUS' then return choice end
 return F.ClientLanguage()
end
F.language=F.ClientLanguage()
function F.Translate(value)
 if F.language~='enUS' or type(value)~='string' then return value end
 if F.english[value] then return F.english[value] end
 if cache[value] then return cache[value] end
 -- Replace literal fragments, longest first; no Lua pattern matching on UTF-8.
 if not value:find('[\208\209]') then return value end
 local translated=value
 for _,ru in ipairs(sorted) do
  local start=1;local pieces={}
  while true do
   local a,b=translated:find(ru,start,true)
   if not a then pieces[#pieces+1]=translated:sub(start);break end
   pieces[#pieces+1]=translated:sub(start,a-1);pieces[#pieces+1]=F.english[ru];start=b+1
  end
  translated=table.concat(pieces)
 end
 if count>=512 then cache={};count=0 end
 cache[value]=translated;count=count+1
 return translated
end
function F.LocalizeText(widget)
 local original=widget.SetText
 widget.SetText=function(self,value,...)
  F.localeLabels[self]={value=value,set=original}
  return original(self,F.Translate(value),...)
 end
 return widget
end
function F.SetLanguage(choice)
 if choice~='ruRU' and choice~='enUS' then choice='auto' end
 if F.engine then F.engine.db.settings.language=choice end
 F.language=F.EffectiveLanguage(choice);cache={};count=0
 for widget,label in pairs(F.localeLabels) do label.set(widget,F.Translate(label.value)) end
 if F.UI and F.UI.card then
  F.UI:RefreshSettings()
  F.Draw()
 end
end
